import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const schemaPath = path.join(root, "docs/personal_finance_canonical_schema_v1.0.json");
const outputPath = path.join(root, "src/application/editorDescriptor.generated.ts");
const objectTypes = ["Household", "Person", "Account", "Income", "Expense", "Asset", "Liability", "Investment", "Assumption", "Scenario"];

const schema = JSON.parse(await readFile(schemaPath, "utf8"));
const descriptor = Object.fromEntries(objectTypes.map((objectType) => {
  const model = schema.object_model[objectType];
  if (!model) throw new Error(`Missing canonical object model ${objectType}`);
  return [objectType, {
    collection: objectType,
    idField: `${objectType.toLowerCase()}_id`,
    fields: Object.fromEntries(Object.entries(model.fields).map(([name, field]) => [name, {
      type: field.type,
      required: field.required,
      default: field.default,
      ...(field.enum === undefined ? {} : { enum: field.enum, enumValues: schema.enums[field.enum] }),
      ...(field.ref === undefined ? {} : { ref: field.ref }),
      ...(field.unit === undefined ? {} : { unit: field.unit }),
      derived: field.derived,
      mutable: field.mutable,
    }])),
  }];
}));

const output = `// Generated by tools/generate-editor-descriptor.mjs from the canonical schema.\n` +
  `// UI metadata only; this file is not financial execution authority.\n` +
  `export const PERSONAL_EDITOR_DESCRIPTOR = ${JSON.stringify(descriptor, null, 2)} as const;\n`;

if (process.argv.includes("--check")) {
  const current = await readFile(outputPath, "utf8").catch(() => "");
  if (current !== output) {
    console.error("Personal editor descriptor drifted from the canonical schema. Run npm run editor:generate.");
    process.exitCode = 1;
  }
} else {
  await writeFile(outputPath, output);
}
