import { describe, expect, it } from "vitest";
import { compileHouseholdTax } from "../src/application/compiler/tax.js";
import { compileHouseholdProjection } from "../src/application/compiler/householdProjection.js";
import { recordAnnualFinancialFact, resolveAnnualFinancialFact, isFactRecord } from "../src/application/financialFacts.js";
import { withAnnualFilingStatus, withContributionYearSchedule } from "../src/application/contributionYearFacts.js";
import { contributionPolicyAt } from "../src/simulation/contributionProjection.js";
import { createHouseholdTaxParticipant } from "../src/simulation/tax/participant.js";
import { runHouseholdKernel, replayHouseholdForecastWindow } from "../src/simulation/householdExecution.js";
import { createPortableHouseholdReplayArtifact, restorePortableHouseholdReplayArtifact } from "../src/simulation/r3/replayArtifact.js";
import { compileHouseholdKernel } from "../src/simulation/r3/compiledHousehold.js";
import { canonicalSerialize } from "../src/simulation/run.js";
import { resolveTaxCoreRule } from "../src/rules/tax/catalog.js";
import { instant } from "../src/time/index.js";
import { getPersonalPurchasePlans, exportPersonalModelJson, importPersonalModelJson } from "../src/application/personalMvp.js";
import { GOLDEN_HOUSEHOLD_IDS as golden } from "../src/application/goldenHousehold.js";
import { createD1IntegratedHousehold, d1IntegratedCompilerRequest, d1IntegratedRunContext, integratedId } from "./fixtures/d1IntegratedHousehold.js";
import { taxHouseholdFixture } from "./fixtures/t1aTaxHouseholds.js";

const scope = (year: number) => ({ personId: golden.person, householdId: golden.household, taxYear: year });
const compile = (model = createD1IntegratedHousehold(), options = {}) => {
  const result = compileHouseholdTax(model, { asOf: "2026-01-01", simulationStart: "2026-01-01", simulationEnd: "2029-01-01", projectedCurrentLawThrough: "2029-01-01", ...options });
  if (result.status !== "compiled") throw new Error(JSON.stringify(result.diagnostics));
  return result.value;
};
describe("U1 one annual household filing authority", () => {
  it("anchors legacy status to only the explicit opening year and never a wall-clock/default year", () => {
    const original = createD1IntegratedHousehold();
    const model = { ...original, objects: { ...original.objects, PrimitiveInstance: original.objects.PrimitiveInstance!.filter(item => !isFactRecord(item) || !isFactRecord(item.parameters) || item.parameters.adapter !== "d1-personal-purchase/v1") } };
    const tax = compile(model);
    expect(tax.filingStatuses).toMatchObject({ "2026": { status: "known", value: "single" }, "2027": { status: "missing" }, "2028": { status: "missing" } });
    expect(compileHouseholdTax(model).status).toBe("compiled");
    const unanchored = compileHouseholdTax(model);
    if (unanchored.status !== "compiled") throw new Error("Expected scoped incomplete tax input");
    expect(Object.values(unanchored.value.filingStatuses!).every(row => row.status === "missing")).toBe(true);
    expect(compile(model, { asOf: undefined, simulationStart: "2027-01-01" }).filingStatuses!["2027"]).toMatchObject({ status: "known", value: "single" });
    expect(compile(model, { asOf: "2026-01-01", simulationStart: "2027-01-01" }).filingStatuses!["2027"]!.status).toBe("missing");
  });
  it("selects the exact same dated fact for tax law and IRA capacity, without touching history", () => {
    const original = createD1IntegratedHousehold();
    const model = recordAnnualFinancialFact(original, { id: integratedId(880), field: "filingStatus", scope: scope(2027), value: "married_joint", provenance: "assumption", reconciledSources: [] });
    const tax = compile(model), fact = tax.filingStatuses!["2027"]!;
    const policy = getPersonalPurchasePlans(model).find(row => row.contribution)!.contribution!;
    const future = contributionPolicyAt(withContributionYearSchedule(model, policy, "2026-01-01", "2029-01-01", "2026-01-01"), instant("2027-06-01T00:00:00.000Z"));
    expect(future.facts.filingStatus).toBe(fact.value);
    expect(fact.sources.map(source => source.id)).toContain(integratedId(880));
    expect(fact.sources).toEqual(expect.arrayContaining([expect.objectContaining({ id: integratedId(880), provenance: "assumption" })]));
    const facts = { residenceJurisdictions: ["US:NY"], workJurisdictions: ["US:NY"], eligibility: { federal_base_deduction_only: true } };
    expect(resolveTaxCoreRule(tax.catalog, "US:FEDERAL", fact.value!, instant("2027-06-01T00:00:00.000Z"), facts).rule.filingStatus).toBe("married_joint");
    expect(withAnnualFilingStatus(model, policy, "2026-01-01").facts.filingStatus).toBe("single");
    expect(model.objects.Account).toEqual(original.objects.Account);
    expect(model.objects.Transaction).toEqual(original.objects.Transaction);
    expect(importPersonalModelJson(exportPersonalModelJson(model))).toEqual(model);
    expect(compile(importPersonalModelJson(exportPersonalModelJson(model))).filingStatuses).toEqual(tax.filingStatuses);
  });
  it("coalesces matching sources and requires explicit reconciliation of different named authorities", () => {
    const original = createD1IntegratedHousehold();
    const model = { ...original, objects: { ...original.objects, Household: original.objects.Household!.map(item => isFactRecord(item) ? { ...item, filing_status: "married_joint" } : item) } };
    const resolved = resolveAnnualFinancialFact(model, "filingStatus", scope(2026), "2026-01-01");
    expect(resolved.status).toBe("true_conflict");
    expect(new Set(resolved.sources.map(source => source.value))).toEqual(new Set(["single", "married_joint"]));
    expect(compile(model).filingStatuses!["2026"]!.status).toBe("true_conflict");
    expect(() => recordAnnualFinancialFact(model, { id: integratedId(881), field: "filingStatus", scope: scope(2026), value: "single", openingReference: "2026-01-01", reconciledSources: [] })).toThrow("CONFIRM_SOURCES");
    const fixed = recordAnnualFinancialFact(model, { id: integratedId(881), field: "filingStatus", scope: scope(2026), value: "single", openingReference: "2026-01-01", reconciledSources: resolved.sources.map(source => source.id) });
    expect(compile(fixed).filingStatuses!["2026"]).toMatchObject({ status: "known", value: "single" });
    expect(fixed.objects.Household).toEqual(model.objects.Household);
    expect(fixed.objects.Person).toEqual(original.objects.Person);
  });
  it("round-trips new annual provenance and summary/detail while keeping legacy v1 replay exact", () => {
    const model = createD1IntegratedHousehold();
    const compiled = compileHouseholdProjection(model, d1IntegratedCompilerRequest());
    if (compiled.status !== "compiled") throw new Error(JSON.stringify(compiled.diagnostics));
    expect(compiled.value.participants![0]!.portableCodec).toBe("household-tax/v2");
    const summary = runHouseholdKernel({ kernel: compiled.value.executionKernel!, runContext: d1IntegratedRunContext() });
    const restored = restorePortableHouseholdReplayArtifact(structuredClone(createPortableHouseholdReplayArtifact(summary)));
    const rerun = runHouseholdKernel({ kernel: restored.replay.kernel, runContext: restored.replay.runContext });
    expect(canonicalSerialize(rerun.state)).toBe(canonicalSerialize(summary.state));
    expect(rerun.periods).toEqual(summary.periods);
    expect(replayHouseholdForecastWindow(restored, summary.periods[0]!.period)).toEqual(replayHouseholdForecastWindow(summary, summary.periods[0]!.period));
    const legacy = taxHouseholdFixture();
    expect(createHouseholdTaxParticipant(legacy.input).portableCodec).toBe("household-tax/v1");
    const oldRun = runHouseholdKernel({ kernel: legacy.kernel, runContext: legacy.context });
    const oldRestored = restorePortableHouseholdReplayArtifact(structuredClone(createPortableHouseholdReplayArtifact(oldRun)));
    const oldRerun = runHouseholdKernel({ kernel: oldRestored.replay.kernel, runContext: oldRestored.replay.runContext });
    expect(oldRerun.runMetadata).toEqual(oldRun.runMetadata);
    expect(oldRerun.state).toEqual(oldRun.state);
    expect(oldRerun.periods).toEqual(oldRun.periods);
    expect(oldRerun.diagnostics).toEqual(oldRun.diagnostics);
    const missing = { ...legacy.input, filingStatuses: {} };
    const { filingStatus: _fixed, ...fresh } = missing;
    const freshKernel = compileHouseholdKernel({ ...legacy.compiled, participants: [createHouseholdTaxParticipant(fresh)] }, legacy.context.simulationStart);
    const freshRun = runHouseholdKernel({ kernel: freshKernel, runContext: legacy.context });
    expect(freshRun.diagnostics).toEqual(expect.arrayContaining([expect.objectContaining({ category: "filing_status_year_unknown", taxYear: "2024" })]));
    expect(freshRun.periods[0]!.cash).toEqual(oldRun.periods[0]!.cash);
    expect(freshRun.periods[0]!.liabilities.isZero()).toBe(true);
  });
});
